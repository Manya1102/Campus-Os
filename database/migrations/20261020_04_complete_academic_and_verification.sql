  ADD COLUMN IF NOT EXISTS eligible_program_id integer;
ALTER TABLE events
  ADD COLUMN IF NOT EXISTS audience varchar(20) NOT NULL DEFAULT 'everyone',
  ADD COLUMN IF NOT EXISTS eligible_program_id integer;

