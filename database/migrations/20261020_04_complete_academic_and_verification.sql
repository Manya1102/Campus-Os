  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'opportunities'::regclass AND conname = 'opportunities_audience_check') THEN
    ALTER TABLE opportunities ADD CONSTRAINT opportunities_audience_check CHECK (audience IN ('everyone', 'students', 'faculty'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'events'::regclass AND conname = 'events_audience_check') THEN
    ALTER TABLE events ADD CONSTRAINT events_audience_check CHECK (audience IN ('everyone', 'students', 'faculty'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'resources'::regclass AND conname = 'fk_resources_program') THEN
    ALTER TABLE resources ADD CONSTRAINT fk_resources_program FOREIGN KEY (eligible_program_id) REFERENCES programs(id) ON DELETE SET NULL;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'opportunities'::regclass AND conname = 'fk_opportunities_program') THEN
    ALTER TABLE opportunities ADD CONSTRAINT fk_opportunities_program FOREIGN KEY (eligible_program_id) REFERENCES programs(id) ON DELETE SET NULL;
