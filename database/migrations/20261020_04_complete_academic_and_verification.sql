-- Structured academic hierarchy, audience targeting, and affiliation roster.
CREATE TABLE IF NOT EXISTS programs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id integer NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
  name varchar(100) NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_program_department_name UNIQUE (department_id, name)
);

CREATE TABLE IF NOT EXISTS class_sections (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_id integer NOT NULL REFERENCES programs(id) ON DELETE CASCADE,
  year smallint NOT NULL,
  semester smallint NOT NULL,
  section_name varchar(30) NOT NULL DEFAULT 'A',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_class_section UNIQUE (program_id, year, semester, section_name)
);

ALTER TABLE students
  ALTER COLUMN program TYPE varchar(100),
  ALTER COLUMN program SET DEFAULT 'B.Tech',
  ALTER COLUMN program SET NOT NULL,
  ADD COLUMN IF NOT EXISTS program_id integer,
  ADD COLUMN IF NOT EXISTS class_section_id integer;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'students'::regclass AND conname = 'fk_students_program') THEN
    ALTER TABLE students ADD CONSTRAINT fk_students_program FOREIGN KEY (program_id) REFERENCES programs(id) ON DELETE SET NULL;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'students'::regclass AND conname = 'fk_students_class_section') THEN
    ALTER TABLE students ADD CONSTRAINT fk_students_class_section FOREIGN KEY (class_section_id) REFERENCES class_sections(id) ON DELETE SET NULL;
  END IF;
END $$;

INSERT INTO programs (department_id, name)
SELECT DISTINCT department_id, program FROM students
ON CONFLICT (department_id, name) DO NOTHING;

UPDATE students AS st
SET program_id = p.id
FROM programs AS p
WHERE p.department_id = st.department_id AND p.name = st.program
  AND st.program_id IS NULL;

INSERT INTO class_sections (program_id, year, semester, section_name)
SELECT DISTINCT program_id, year, semester, 'A'
FROM students WHERE program_id IS NOT NULL
ON CONFLICT (program_id, year, semester, section_name) DO NOTHING;

UPDATE students AS st
SET class_section_id = cs.id
FROM class_sections AS cs
WHERE cs.program_id = st.program_id AND cs.year = st.year
  AND cs.semester = st.semester AND cs.section_name = 'A'
  AND st.class_section_id IS NULL;

CREATE TABLE IF NOT EXISTS subject_offerings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  class_section_id integer NOT NULL REFERENCES class_sections(id) ON DELETE CASCADE,
  faculty_id integer REFERENCES faculty(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_subject_section UNIQUE (subject_id, class_section_id)
);

INSERT INTO subject_offerings (subject_id, class_section_id, faculty_id)
SELECT DISTINCT e.subject_id, st.class_section_id, sub.faculty_id
FROM enrollments AS e
JOIN students AS st ON st.id = e.student_id
JOIN subjects AS sub ON sub.id = e.subject_id
WHERE st.class_section_id IS NOT NULL
ON CONFLICT (subject_id, class_section_id) DO NOTHING;

ALTER TABLE resources
  ADD COLUMN IF NOT EXISTS audience varchar(20) NOT NULL DEFAULT 'everyone',
  ADD COLUMN IF NOT EXISTS eligible_program_id integer;
ALTER TABLE opportunities
