-- Institution-level academic calendar.
CREATE TABLE IF NOT EXISTS academic_calendar_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id integer NOT NULL REFERENCES universities(id) ON DELETE CASCADE,
  title varchar(200) NOT NULL,
  category varchar(30) NOT NULL DEFAULT 'Other'
    CHECK (category IN ('Term dates', 'Examination', 'Registration', 'Holiday', 'Other')),
  starts_on date NOT NULL,
  ends_on date,
  description text,
  audience varchar(20) NOT NULL DEFAULT 'everyone'
    CHECK (audience IN ('everyone', 'students', 'faculty')),
  eligible_program_id integer REFERENCES programs(id) ON DELETE SET NULL,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_calendar_university_dates
  ON academic_calendar_items (university_id, starts_on, ends_on);
