-- Supabase/PostgreSQL schema for Campus OS.
-- Run once in the Supabase SQL Editor on a new project. This file does not
-- create or drop the database; Supabase has already selected the database.
-- Connect the Express backend using its server-only DATABASE_URL setting.

CREATE TABLE universities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(200) NOT NULL,
  city varchar(100),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE colleges (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id integer NOT NULL REFERENCES universities(id) ON DELETE CASCADE,
  name varchar(200) NOT NULL
);

CREATE TABLE departments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  college_id integer NOT NULL REFERENCES colleges(id) ON DELETE CASCADE,
  name varchar(200) NOT NULL
);

CREATE TABLE programs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id integer NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
  name varchar(100) NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_program_department_name UNIQUE (department_id, name)
);

CREATE TABLE class_sections (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_id integer NOT NULL REFERENCES programs(id) ON DELETE CASCADE,
  year smallint NOT NULL,
  semester smallint NOT NULL,
  section_name varchar(30) NOT NULL DEFAULT 'A',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_class_section UNIQUE (program_id, year, semester, section_name)
);

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(255) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  full_name varchar(150) NOT NULL,
  role varchar(30) NOT NULL DEFAULT 'student'
    CHECK (role IN ('student', 'faculty', 'admin', 'platform_admin')),
  account_status varchar(20) NOT NULL DEFAULT 'active'
    CHECK (account_status IN ('pending', 'active', 'rejected')),
  affiliation_verified_at timestamp,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE students (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  department_id integer NOT NULL REFERENCES departments(id),
  roll_number varchar(50) NOT NULL,
  program varchar(100) NOT NULL DEFAULT 'B.Tech',
  program_id integer REFERENCES programs(id) ON DELETE SET NULL,
  class_section_id integer REFERENCES class_sections(id) ON DELETE SET NULL,
  year smallint NOT NULL,
  semester smallint NOT NULL,
  CONSTRAINT uq_roll_in_department UNIQUE (department_id, roll_number)
);

CREATE TABLE faculty (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  department_id integer NOT NULL REFERENCES departments(id),
  designation varchar(100)
);

CREATE TABLE admin_profiles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  university_id integer NOT NULL REFERENCES universities(id) ON DELETE CASCADE,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE affiliation_roster (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id integer NOT NULL REFERENCES universities(id) ON DELETE CASCADE,
  department_id integer NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
  role varchar(20) NOT NULL CHECK (role IN ('student', 'faculty')),
  institutional_id varchar(100) NOT NULL,
  email varchar(255) NOT NULL,
  program_id integer REFERENCES programs(id) ON DELETE SET NULL,
  year smallint,
  semester smallint,
  section_name varchar(30) DEFAULT 'A',
  designation varchar(100),
  invite_code_hash char(64),
  claimed_by integer REFERENCES users(id) ON DELETE SET NULL,
  claimed_at timestamp,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_roster_identity UNIQUE (university_id, role, institutional_id),
  CONSTRAINT uq_roster_email UNIQUE (university_id, email)
);

CREATE TABLE subjects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id integer NOT NULL REFERENCES departments(id),
  code varchar(20) NOT NULL,
  name varchar(150) NOT NULL,
  semester smallint NOT NULL,
  faculty_id integer REFERENCES faculty(id) ON DELETE SET NULL
);

CREATE TABLE enrollments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  CONSTRAINT uq_enrollment UNIQUE (student_id, subject_id)
);

CREATE TABLE subject_offerings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  class_section_id integer NOT NULL REFERENCES class_sections(id) ON DELETE CASCADE,
  faculty_id integer REFERENCES faculty(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_subject_section UNIQUE (subject_id, class_section_id)
);

CREATE TABLE timetable (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  day_of_week varchar(3) NOT NULL CHECK (day_of_week IN ('Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat')),
  start_time time NOT NULL,
  end_time time NOT NULL,
  room varchar(50),
  class_type varchar(20) NOT NULL DEFAULT 'Lecture'
    CHECK (class_type IN ('Lecture', 'Practical', 'Tutorial'))
);

CREATE TABLE assignments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  title varchar(200) NOT NULL,
  description text,
  due_date date NOT NULL,
  priority varchar(10) NOT NULL DEFAULT 'Medium' CHECK (priority IN ('Low', 'Medium', 'High')),
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE assignment_submissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  status varchar(20) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Completed')),
  completed_at timestamp,
  CONSTRAINT uq_submission UNIQUE (assignment_id, student_id)
);

CREATE TABLE attendance (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  subject_id integer NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  class_date date NOT NULL,
  status varchar(10) NOT NULL CHECK (status IN ('present', 'absent', 'late')),
  marked_by integer REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT uq_attendance UNIQUE (student_id, subject_id, class_date)
);

CREATE TABLE announcements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id integer NOT NULL REFERENCES universities(id) ON DELETE CASCADE,
  college_id integer REFERENCES colleges(id) ON DELETE CASCADE,
  department_id integer REFERENCES departments(id) ON DELETE CASCADE,
  category varchar(20) NOT NULL DEFAULT 'General'
    CHECK (category IN ('Academic', 'Event', 'Department', 'General')),
  title varchar(200) NOT NULL,
  body text NOT NULL,
  audience varchar(100) NOT NULL DEFAULT 'All Students',
  pinned boolean NOT NULL DEFAULT false,
  posted_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id integer NOT NULL REFERENCES universities(id) ON DELETE CASCADE,
  title varchar(200) NOT NULL,
  category varchar(50) NOT NULL,
  description text,
  location varchar(150),
  seats_info varchar(100),
  starts_at timestamp NOT NULL,
  ends_at timestamp,
  visibility varchar(20) NOT NULL DEFAULT 'university'
    CHECK (visibility IN ('university', 'cross_campus')),
  audience varchar(20) NOT NULL DEFAULT 'everyone'
    CHECK (audience IN ('everyone', 'students', 'faculty')),
  eligible_program_id integer REFERENCES programs(id) ON DELETE SET NULL
);

CREATE TABLE event_registrations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_registration UNIQUE (event_id, user_id)
);

CREATE TABLE academic_calendar_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id integer NOT NULL REFERENCES universities(id) ON DELETE CASCADE,
  title varchar(200) NOT NULL,
  category varchar(30) NOT NULL DEFAULT 'Other'
    CHECK (category IN ('Term dates', 'Examination', 'Registration', 'Holiday', 'Other')),
  starts_on date NOT NULL,
  ends_on date,
  description text,
  audience varchar(20) NOT NULL DEFAULT 'everyone'
    CHECK (audience IN ('everyone', 'students', 'faculty')),
  eligible_program_id integer REFERENCES programs(id) ON DELETE SET NULL,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_calendar_university_dates ON academic_calendar_items (university_id, starts_on, ends_on);

CREATE TABLE resources (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id integer REFERENCES universities(id) ON DELETE CASCADE,
  visibility varchar(20) NOT NULL DEFAULT 'cross_campus'
    CHECK (visibility IN ('university', 'cross_campus')),
  audience varchar(20) NOT NULL DEFAULT 'everyone'
    CHECK (audience IN ('everyone', 'students', 'faculty')),
  eligible_program_id integer REFERENCES programs(id) ON DELETE SET NULL,
  title varchar(200) NOT NULL,
  subject varchar(100) NOT NULL,
  type varchar(20) NOT NULL CHECK (type IN ('Notes', 'Practice', 'Tutorial')),
  format varchar(50) NOT NULL,
  description text,
  author varchar(150),
  icon varchar(16),
  url varchar(500),
  uploaded_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE opportunities (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  university_id integer REFERENCES universities(id) ON DELETE CASCADE,
  visibility varchar(20) NOT NULL DEFAULT 'cross_campus'
    CHECK (visibility IN ('university', 'cross_campus')),
  audience varchar(20) NOT NULL DEFAULT 'students'
    CHECK (audience IN ('everyone', 'students', 'faculty')),
  eligible_program_id integer REFERENCES programs(id) ON DELETE SET NULL,
  title varchar(200) NOT NULL,
  company varchar(150) NOT NULL,
  type varchar(20) NOT NULL CHECK (type IN ('Internship', 'Training', 'Competition')),
  mode varchar(30) NOT NULL,
  location varchar(100) NOT NULL,
  stipend varchar(100),
  deadline date NOT NULL,
  category varchar(50) NOT NULL,
  description text,
  skills jsonb NOT NULL DEFAULT '[]'::jsonb,
  application_url varchar(500),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE saved_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  item_type varchar(20) NOT NULL CHECK (item_type IN ('resource', 'event', 'opportunity')),
  item_id integer NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_saved UNIQUE (user_id, item_type, item_id)
);

-- Initial directory values keep public signup usable. Continue configuring the
-- real institution from the admin dashboard after the backend is connected.
WITH new_university AS (
  INSERT INTO universities (name, city) VALUES ('Campus University', 'Pune') RETURNING id
), new_college AS (
  INSERT INTO colleges (university_id, name)
  SELECT id, 'College of Engineering' FROM new_university RETURNING id
)
INSERT INTO departments (college_id, name)
SELECT id, 'Computer Science' FROM new_college
UNION ALL
SELECT id, 'Electronics and Communication' FROM new_college;

